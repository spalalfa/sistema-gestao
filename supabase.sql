create extension if not exists pgcrypto;

create table if not exists public.funcionarios (
 id uuid primary key default gen_random_uuid(),
 created_at timestamptz not null default now(), updated_at timestamptz,
 matricula varchar(6) unique not null check (matricula ~ '^[0-9]{6}$'),
 nome text not null, funcao text not null, codigo_funcao text, equipe text,
 data_admissao date, situacao text not null default 'ATIVO' check (situacao in ('ATIVO','DESLIGADO','AFASTADO')),
 cpf text, rg text, pis text, data_nascimento date, celular text, email text,
 cep text, endereco text, numero text, complemento text, observacao text
);
create table if not exists public.frota (
 id uuid primary key default gen_random_uuid(), created_at timestamptz not null default now(), updated_at timestamptz,
 placa text unique not null, modelo text not null, marca text, ano integer, tipo text,
 situacao text not null default 'ATIVO' check (situacao in ('ATIVO','MANUTENÇÃO','INOPERANTE')),
 quilometragem numeric, validade_documento date, observacao text
);
create table if not exists public.equipamentos (
 id uuid primary key default gen_random_uuid(), created_at timestamptz not null default now(), updated_at timestamptz,
 codigo text unique not null, nome text not null, categoria text, marca_modelo text,
 situacao text not null default 'ATIVO' check (situacao in ('ATIVO','MANUTENÇÃO','INOPERANTE')),
 data_aquisicao date, validade date, observacao text
);
create table if not exists public.usuarios_perfil (
 id uuid primary key references auth.users(id) on delete cascade,
 nome text not null, cargo text, departamento text,
 permissoes jsonb not null default '{"visao_geral":true}'::jsonb,
 created_at timestamptz not null default now()
);
create table if not exists public.lancamentos_ferias (
 id uuid primary key default gen_random_uuid(), created_at timestamptz not null default now(),
 matricula varchar(6) not null, funcionario text not null, funcao text, admissao date,
 periodo_aquisitivo text, quantidade_dias integer, inicio_gozo date, fim_gozo date, data_retorno date, observacao text
);
create table if not exists public.lancamentos_medicos (
 id uuid primary key default gen_random_uuid(), created_at timestamptz not null default now(),
 numero_registro bigint generated by default as identity, data_entrega date not null, matricula varchar(6) not null,
 funcionario text not null, funcao text, admissao date, tipo text not null, data_ocorrido date, crm_cro text,
 especialidade text, cid10 text, afastamento text, apto text, dias_afastamento integer, data_retorno date,
 local_atendimento text, observacao text
);
create table if not exists public.lancamentos_faltas (
 id uuid primary key default gen_random_uuid(), created_at timestamptz not null default now(),
 numero_registro bigint generated by default as identity, data_inclusao date not null, matricula varchar(6) not null,
 funcionario text not null, funcao text, admissao date, data_ausencia date not null, motivo text, observacao text
);
create table if not exists public.lancamentos_disciplinares (
 id uuid primary key default gen_random_uuid(), created_at timestamptz not null default now(),
 numero_registro bigint generated by default as identity, data_inclusao date not null, matricula varchar(6) not null,
 funcionario text not null, funcao text, data_ocorrido date, tipo text not null, motivo text not null,
 dias_afastamento integer, data_retorno date, aplicado_por text, testemunha1 text, testemunha2 text, observacao text
);
create table if not exists public.lancamentos_materiais (
 id uuid primary key default gen_random_uuid(), created_at timestamptz not null default now(),
 numero_registro bigint generated by default as identity, data_inclusao date not null, matricula varchar(6) not null,
 funcionario text not null, data_entrega date not null, tipo text not null, tamanho text,
 status_item text not null check (status_item in ('NOVO','USADO')), quantidade numeric not null default 1,
 ca text, validade date, observacao text
);

